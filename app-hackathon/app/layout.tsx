import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import { Providers } from "./providers";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "APU - Privacy-Preserving Health Data",
  description: "Aggregate health statistics while preserving individual privacy with FHE",
};

// Fully client-rendered dApp (wallet + FHE SDK) — render on demand, don't statically prerender at build.
// Pattern from ghostlend (mainnet-s3 winner): prevents Next.js from trying to prerender pages with providers.
export const dynamic = "force-dynamic";

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en">
      <body
        className={`${geistSans.variable} ${geistMono.variable} antialiased`}
      >
        <Providers>{children}</Providers>
      </body>
    </html>
  );
}
